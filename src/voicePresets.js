/**
 * D&D creature voices built from layered DSP rather than samples.
 *
 * Layer macros (0–1 unless noted):
 *   pitch     semitones of the main body voice
 *   formant   semitones of vocal-tract size (negative = bigger throat)
 *   sub       octave-down weight (mass, chest)
 *   detune    doubled voice (thickness, "more than one speaker")
 *   ring      inharmonic shimmer via frequency shifting (alien / metallic)
 *   ringFreq  Hz of that shift
 *   growl     throat roughness via 25–90 Hz amplitude modulation
 *   growlRate Hz of the growl
 *   air       breath noise opened by your own voice envelope
 *   airFreq   Hz centre of that breath
 *   drive     saturation
 *
 * Tone: low / mid / high (dB), presence (+dB at presenceFreq)
 * Space: chorus / vibrato / delay / reverb
 * Range: highpass / lowpass (Hz), gain
 */

