export function getVoicePresetById(presetId) {
  return voicePresets.find((preset) => preset.id === presetId) || null;
}

export function getVoiceCategories() {
  const categories = [];
  const seen = new Set();
  for (const preset of voicePresets) {
    if (seen.has(preset.category)) continue;
    seen.add(preset.category);
    categories.push(preset.category);
  }
  return categories;
}

export function resolveVoiceParams(basePreset, overrides = {}) {
  return {
    ...DEFAULT_VOICE_PARAMS,
    ...(basePreset || {}),
    ...overrides,
    id: overrides.id || basePreset?.id || "custom",
    name: overrides.name || basePreset?.name || "Custom",
    category: overrides.category || basePreset?.category || "Custom",
  };
}
